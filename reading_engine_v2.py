def assess_question_context(spread_type: str, user_question: str) -> dict[str, str]:
    """Decide whether a reading has enough concrete context to be useful.

    This is deliberately conservative: only clearly broad questions are paused.
    It performs no AI call and never tries to infer the user's hidden situation.
    """
    question = " ".join((user_question or "").lower().replace("ё", "е").split())

    if spread_type == "daily_card":
        return {"status": "ready", "clarifying_question": "", "reason": ""}

    has_broad_marker = any(marker in question for marker in BROAD_QUESTION_MARKERS)
    has_detail_marker = any(marker in question for marker in CONTEXT_DETAIL_MARKERS)
    has_concrete_detail = has_detail_marker or len(question.split()) >= 12

    if has_broad_marker and not has_concrete_detail:
        return {
            "status": "needs_clarification",
            "clarifying_question": CLARIFICATION_QUESTIONS.get(
                spread_type,
                CLARIFICATION_QUESTIONS["personal_question"],
            ),
            "reason": "В вопросе пока не названа конкретная ситуация или сфера.",
        }

    return {"status": "ready", "clarifying_question": "", "reason": ""}


def prepare_cards_with_positions(
    cards: list[dict[str, Any]],
    spread_type: str,
    topic: str = "general",
) -> list[dict[str, Any]]:
    """Attach a meaningful spread position and safe source data to every card."""
    positions = SPREAD_POSITIONS.get(spread_type, [])
    prepared = []

    for index, card in enumerate(cards):
        position = (
            positions[index]
            if index < len(positions)
            else f"Дополнительный акцент {index + 1}"
        )

        prepared.append(
            {
                "position": position,
                "name": card["name"],
                "general_meaning": card.get("general", ""),
                "topic_meaning": card.get(topic, card.get("general", "")),
                "reflection_question": card.get("question", ""),
                "practical_focus": card.get("advice", ""),
                "tags": card.get("tags", []),
            }
        )

    return prepared


def format_cards_for_prompt(cards_with_positions: list[dict[str, Any]]) -> str:
    blocks = []

    for index, item in enumerate(cards_with_positions, start=1):
        tags = ", ".join(item.get("tags", [])) or "нет"

        blocks.append(
            "\n".join(
                [
                    f"{index}. Позиция: {item['position']}",
                    f"Карта: {item['name']}",
                    f"Основная символика: {item['general_meaning']}",
                    f"Значение для темы: {item['topic_meaning']}",
                    f"Вопрос карты: {item['reflection_question']}",
                    f"Практический фокус: {item['practical_focus']}",
                    f"Теги: {tags}",
                ]
            )
        )

    return "\n\n".join(blocks)


def build_reading_v2_prompt(
    spread_type: str,
    user_question: str,
    cards: list[dict[str, Any]],
    topic: str = "general",
) -> str:
    """Build a complete production prompt from structured spread data."""
    cards_with_positions = prepare_cards_with_positions(cards, spread_type, topic)
    cards_text = format_cards_for_prompt(cards_with_positions)
    spread_instruction = SPREAD_INSTRUCTIONS.get(
        spread_type,
        SPREAD_INSTRUCTIONS["personal_question"],
    )
    output_limit = OUTPUT_LIMITS.get(spread_type, "220–350 слов")

